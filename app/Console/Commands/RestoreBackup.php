<?php

namespace App\Console\Commands;

use App\Models\SystemBackup;
use App\Services\BackupService;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Storage;

#[Signature('clinic:restore {backupId? : The ID of the backup to restore (omit when using --latest)} {--latest : Restore the most recent completed backup} {--force : Skip confirmation prompt}')]
#[Description('Restore a database backup')]
class RestoreBackup extends Command
{
    public function __construct(
        private readonly BackupService $backupService
    ) {
        parent::__construct();
    }

    /**
     * Execute the console command.
     */
    public function handle(): int
    {
        $backupId = $this->argument('backupId');
        $force = $this->option('force');
        $useLatest = $this->option('latest');

        if ($useLatest) {
            $backup = SystemBackup::query()
                ->completed()
                ->orderByDesc('created_at')
                ->orderByDesc('id')
                ->first();

            if (! $backup) {
                $this->error('No completed backup found to restore.');
                $this->info('List available backups with: php artisan clinic:list-backups');
                $this->info('Archives present on the backup disk:');
                $this->printBackupDiskArchives();

                return Command::FAILURE;
            }
        } elseif ($backupId !== null) {
            $backup = SystemBackup::find((int) $backupId);
        } else {
            $this->error('Specify a backup ID or pass --latest.');

            return Command::FAILURE;
        }

        if (! $backup) {
            $this->error('Backup #'.($backupId ?? '?').' not found.');

            return Command::FAILURE;
        }

        if ($backup->status !== SystemBackup::STATUS_COMPLETED) {
            $this->error("Backup #{$backup->id} is not completed (status: {$backup->status}).");

            return Command::FAILURE;
        }

        $this->info('Backup Details:');
        $this->table(
            ['Property', 'Value'],
            [
                ['ID', $backup->id],
                ['Filename', $backup->filename],
                ['Size', $this->backupService->formatBytes($backup->file_size)],
                ['Checksum', $backup->checksum_sha256 ?? 'N/A'],
                ['Encrypted', $backup->is_encrypted ? 'Yes' : 'No'],
                ['Created', $backup->created_at?->toDateTimeString()],
                ['Generated By', $backup->generator?->name ?? 'Unknown'],
            ]
        );

        if (! $force) {
            if (! $this->confirm('This will OVERWRITE the current database. Are you sure you want to continue?')) {
                $this->info('Restore cancelled.');

                return Command::SUCCESS;
            }
        }

        $this->info('Starting restore...');

        try {
            $this->backupService->restoreBackup($backup);
            $this->info('Database restored successfully!');

            return Command::SUCCESS;
        } catch (\Throwable $e) {
            $this->error('Restore failed: '.$e->getMessage());

            return Command::FAILURE;
        }
    }

    /**
     * Print the archive files actually present on the backup disk, so an
     * operator can still locate a restore candidate even when the
     * SystemBackup metadata table is gone (fresh server / wiped database).
     */
    private function printBackupDiskArchives(): void
    {
        $diskName = config('filesystems.backup_disk', 'local');

        try {
            $files = Storage::disk($diskName)->allFiles('system');
        } catch (\Throwable) {
            $files = [];
        }

        if ($files === []) {
            $this->info('  (none found)');

            return;
        }

        foreach ($files as $file) {
            $this->info('  - '.$file);
        }

        $this->info('If the system_backups table was lost (fresh server or wiped database),');
        $this->info('follow the manual restore procedure in docs/DISASTER_RECOVERY_RUNBOOK.md.');
    }
}
